// Pathway-side and registry-side totals, published separately.
//
// The two sides of the crosswalk have different denominators — 324 compiled
// pathways and 497 registry tracks — and they do not answer the same question.
// A pathway total says what the runtime offers. A track total says what the
// registry says exists. Reporting one as though it were the other overstates
// coverage, which is why they are generated here side by side and never summed
// into a single "mapped" figure.
//
// Generated from the crosswalk artifact so the numbers cannot drift from it.
//
// Usage:
//   node scripts/generate-rcap-e3-totals.mjs
//   node scripts/generate-rcap-e3-totals.mjs --check

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const crosswalkPath = path.join(rootDir, "data/rcap-ledger/track-pathway-crosswalk.json");
const reportPath = path.join(rootDir, "docs/record-clearing/e3-totals.md");
const check = process.argv.includes("--check");

const crosswalk = JSON.parse(fs.readFileSync(crosswalkPath, "utf8"));
const a = crosswalk.aggregates;

const dispositions = {};
for (const t of crosswalk.registryTracks) {
  dispositions[t.compiledCoverageDisposition] = (dispositions[t.compiledCoverageDisposition] ?? 0) + 1;
}

const pathwaySide = [
  ["direct", a.pathwaysDirect, "compiled pathway is the runtime representation of a registry track"],
  ["variant", a.pathwaysVariant, "a variant of a registry track rather than an exact representation"],
  ["composed", a.pathwaysComposedUnit, "part of a composed unit standing for one track"],
  ["routing/supporting", a.pathwaysRoutingOrSupporting, "routing or supporting path, not relief in itself"],
  ["scoped-out", a.pathwaysScopedOut, "terminal: named authority the registry deliberately does not cover"],
  ["registry-gap", a.pathwaysRegistryGap, "terminal: real relief mechanism with no registry track"],
  ["crosswalk-terminal", a.pathwaysCrosswalkTerminalClassified, "terminal for CROSSWALK purposes only: an E4 lane established that no registry counterpart exists. Closes the mapping question, never the relief question, and carries no launch-ledger effect"],
  ["unresolved", a.pathwaysUnresolved, "no conclusion on the evidence available"]
];
const pathwaySum = pathwaySide.reduce((s, [, n]) => s + n, 0);

const registrySide = [
  ["mapped tracks", a.tracksWithRuntimeCoverage, `${a.tracksExactPathway} exact + ${a.tracksRepresentedByVariants} represented by variants`],
  ["currentness-blocked tracks", a.tracksSupersededRuntimeText, "mapped, but the runtime renders superseded text — excluded from mapped coverage"],
  ["uncompiled tracks", a.tracksMissingFromCompiledRuntime, "terminally classified: no compiled runtime representation exists"],
  ["ambiguous / unresolved tracks", a.tracksUnresolvedAmbiguous, "candidate pathways remain ambiguous"]
];
const registrySum = registrySide.reduce((s, [, n]) => s + n, 0);

const lines = [];
lines.push("# RCAP totals after final E3 — pathway side and registry side");
lines.push("");
lines.push(
  `Generated by \`scripts/generate-rcap-e3-totals.mjs\` from \`data/rcap-ledger/track-pathway-crosswalk.json\` (contentHash \`${crosswalk.contentHash}\`).`
);
lines.push("");
lines.push("## Read this first");
lines.push("");
lines.push(
  `**${a.pathwaysMapped} mapped pathways is not ${a.tracksWithRuntimeCoverage} mapped registry tracks.** They are different denominators counted from different sides. ${a.pathwaysMapped} of ${a.compiledPathways} compiled pathways carry a registry relationship; ${a.tracksWithRuntimeCoverage} of ${a.registryTracks} registry tracks have a runtime representation. Neither number is a coverage percentage of the other, and quoting the pathway figure against the ${a.registryTracks}-track denominator overstates coverage substantially.`
);
lines.push("");
lines.push(`The registry denominator is **${a.registryTracks}** and is not altered by anything in this report.`);
lines.push("");
lines.push(`## Pathway-side totals (denominator ${a.compiledPathways} compiled pathways)`);
lines.push("");
lines.push("| Class | Count | Meaning |");
lines.push("| --- | ---: | --- |");
for (const [name, count, meaning] of pathwaySide) lines.push(`| ${name} | ${count} | ${meaning} |`);
lines.push(`| **total** | **${pathwaySum}** | |`);
lines.push("");
lines.push(
  `Mapped = ${a.pathwaysDirect} + ${a.pathwaysVariant} + ${a.pathwaysComposedUnit} = **${a.pathwaysMapped}**. Terminal = ${a.pathwaysScopedOut} scoped-out + ${a.pathwaysRegistryGap} registry-gap + ${a.pathwaysRoutingOrSupporting} routing = **${a.pathwaysTerminal}**. Unresolved = **${a.pathwaysUnresolved}**.`
);
lines.push("");
lines.push(
  `**Currentness-blocked: ${a.pathwaysCurrencyFlagged}.** This is an overlay, not a class — the flagged pathway is already counted above as mapped. It is listed separately because a correct mapping to repealed runtime text is not current coverage, and adding it as its own row would double-count it.`
);
lines.push("");
lines.push(`## Registry-side totals (denominator ${a.registryTracks} registry tracks)`);
lines.push("");
lines.push("| Class | Count | Meaning |");
lines.push("| --- | ---: | --- |");
for (const [name, count, meaning] of registrySide) lines.push(`| ${name} | ${count} | ${meaning} |`);
lines.push(`| **total** | **${registrySum}** | |`);
lines.push("");
lines.push("Raw coverage dispositions as recorded on each track:");
lines.push("");
lines.push("| Disposition | Tracks |");
lines.push("| --- | ---: |");
for (const [name, count] of Object.entries(dispositions).sort()) lines.push(`| \`${name}\` | ${count} |`);
lines.push("");
lines.push("## Registry-gap-affected tracks");
lines.push("");
lines.push(
  `**0.** The ${a.pathwaysRegistryGap} registry gaps are compiled pathways with no registry track at all, so they consume none of the ${a.registryTracks} tracks. Their effect is on the denominator's future — each is a proposed owner action that would add a track — not on the classification of any existing one. They are counted on the pathway side only.`
);
lines.push("");
lines.push("## Milestone 1 item 2");
lines.push("");
lines.push(
  `**${a.milestone1Item2Closed ? "CLOSED" : "BLOCKED"}** on ${crosswalk.unresolvedIds.compiledPathways.length} unresolved pathways and ${crosswalk.unresolvedIds.registryTracks.length} unresolved registry tracks.`
);
lines.push("");

// --- the seven distinctions --------------------------------------------------
//
// These are seven different questions that all sound like "is it done?". Each
// has its own number and its own evidence, and collapsing any two of them
// overstates readiness. The ladder is ordered: a rung cannot be climbed by
// satisfying a lower one.
lines.push("## Seven questions that are not the same question");
lines.push("");
lines.push(
  "Each rung has its own number and its own evidence. They are ordered: satisfying a lower rung never satisfies a higher one, and quoting one as another is the most likely way this work gets misreported."
);
lines.push("");
lines.push("| # | Question | Current state | What it does NOT tell you |");
lines.push("| ---: | --- | --- | --- |");
lines.push(
  `| 1 | **Source resolution** — does the cited source exist and open? | all 935 citations resolve, 13 read at a pinned commit | nothing about whether the source says what was claimed |`
);
lines.push(
  `| 2 | **Source support** — does the source actually support the claim? | 935 audited rows; 30.2% non-verbatim, 2 high-severity | nothing about whether the law is completely captured |`
);
lines.push(
  `| 3 | **Legal authority completeness** — is the operative primary authority in hand? | 7 official-source obligations open; 2 named non-blocking subsection residuals | nothing about whether a relationship was drawn |`
);
lines.push(
  `| 4 | **Crosswalk relationship** — is the track↔pathway link established? | ${a.pathwaysMapped}/${a.compiledPathways} pathways mapped, ${a.pathwaysTerminal} terminal, ${a.pathwaysUnresolved} unresolved | nothing about whether the runtime text is current |`
);
lines.push(
  `| 5 | **Runtime currentness** — is the text a participant would receive current law? | ${a.tracksSupersededRuntimeText} track renders repealed text and contributes no current coverage | nothing about whether a participant can actually be served |`
);
lines.push(
  `| 6 | **Participant readiness** — can a real person get this relief today? | ${a.tracksMissingFromCompiledRuntime} tracks have no runtime representation at all | nothing about whether the product may launch |`
);
lines.push(
  `| 7 | **Launch terminality** — is this shippable? | not established; staging authorization is not being requested | — |`
);
lines.push("");
lines.push(
  `The clearest trap is rungs 4 and 6. **${a.pathwaysMapped} mapped pathways** is a statement about rung 4 only. A participant eligible under one of the ${a.tracksMissingFromCompiledRuntime} unimplemented tracks receives nothing, no matter how correct the map is; and Oklahoma's clean-slate track is correctly mapped (rung 4) while failing rung 5, which is why it contributes no current coverage and must not be sold.`
);
lines.push("");

const report = `${lines.join("\n")}\n`;

if (pathwaySum !== a.compiledPathways) {
  console.error(`generate-rcap-e3-totals FAILED: pathway classes sum to ${pathwaySum}, not ${a.compiledPathways}`);
  process.exit(1);
}
if (registrySum !== a.registryTracks) {
  console.error(`generate-rcap-e3-totals FAILED: registry classes sum to ${registrySum}, not ${a.registryTracks}`);
  process.exit(1);
}

if (check) {
  const current = fs.existsSync(reportPath) ? fs.readFileSync(reportPath, "utf8") : "";
  if (current !== report) {
    console.error("E3 totals are stale. Run: npm run rcap:e3-totals");
    process.exit(1);
  }
  console.log(`E3 totals current. Pathway side ${pathwaySum}, registry side ${registrySum}.`);
  process.exit(0);
}

fs.writeFileSync(reportPath, report);
console.log(`E3 totals written. Pathway side sums to ${pathwaySum}; registry side sums to ${registrySum}.`);
console.log(`  mapped pathways ${a.pathwaysMapped} of ${a.compiledPathways}; mapped tracks ${a.tracksWithRuntimeCoverage} of ${a.registryTracks} — different denominators, never interchangeable.`);
