// Renders docs/record-clearing/CONTROLLING_LEGAL_DECISIONS_2026-08-28.md from
// the controlling decision record, which is the authority.
//
// Usage: node scripts/generate-controlling-legal-decisions-doc.mjs [--check]

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const CHECK = process.argv.includes("--check");
const IN = "data/record-clearing/legal-decisions/2026-08-28-controlling-decisions.json";
const OUT = "docs/record-clearing/CONTROLLING_LEGAL_DECISIONS_2026-08-28.md";

const record = JSON.parse(fs.readFileSync(path.join(root, IN), "utf8"));

const L = [];
L.push("# Controlling legal decisions — 2026-08-28");
L.push("");
L.push(`**Generated by** \`scripts/generate-controlling-legal-decisions-doc.mjs\` from \`${IN}\`, which is the authority. Do not edit this file by hand.`);
L.push("");
L.push(`**Law reviewed through ${record.reviewedThrough}.** ${record.note}`);
L.push("");
L.push("These four decisions close the four immediate legal assignments. None of them goes back to legal review.");
L.push("");
L.push("| Decision | Jurisdiction | Track | Questions answered | Packet families |");
L.push("|---|---|---|---:|---|");
for (const d of record.decisions) {
  L.push(`| \`${d.decisionId}\` | ${d.jurisdiction} | \`${d.tracks.join(", ")}\` | ${d.originalQuestionText.length} | ${d.affectedPacketFamilies.join(", ")} |`);
}
L.push("");
for (const d of record.decisions) {
  L.push(`## ${d.decisionId}`);
  L.push("");
  L.push(`- **JURISDICTION:** ${d.jurisdiction}`);
  L.push(`- **TRACKS:** ${d.tracks.map((t) => `\`${t}\``).join(", ")}`);
  L.push(`- **PATHWAYS:** ${d.pathways.map((p) => `\`${p}\``).join(", ")}`);
  L.push(`- **ORIGINAL ASSIGNMENT:** ${d.originalAssignmentId}`);
  L.push(`- **REVIEWED THROUGH:** ${d.reviewedThrough}`);
  L.push(`- **EXISTING MEMO:** \`${d.existingMemo.path}\` · sha256 \`${d.existingMemo.sha256}\``);
  L.push(`- **AFFECTED PACKET FAMILIES:** ${d.affectedPacketFamilies.join(", ") || "none"}`);
  L.push("");
  L.push("**ORIGINAL QUESTION TEXT**");
  L.push("");
  for (const q of d.originalQuestionText) L.push(`> ${q}`);
  L.push("");
  L.push("**RECORDED AUTHORITY, exactly as supplied**");
  L.push("");
  for (const line of d.recordedAuthority) L.push(`- ${line}`);
  L.push("");
  L.push(`**SUPERSEDED INTERIM TREATMENT:** ${d.supersededInterimTreatment}`);
  L.push("");
  L.push(`**PRODUCT DISPOSITION:** ${d.productDisposition}`);
  L.push("");
  L.push("**ENGINEERING CONSEQUENCES**");
  L.push("");
  for (const line of d.engineeringConsequences) L.push(`- ${line}`);
  L.push("");
}
L.push("## Executable projection");
L.push("");
L.push("`src/lib/rcap/legal-decisions/controlling-route-effects.ts` is the executable form of these");
L.push("decisions: the consent gate, the effective-date split, the filing-code rule, the clerk gate, the");
L.push("fee schedule and the retirement. `scripts/verify-controlling-legal-decisions.mjs` exercises it,");
L.push("so the decisions are behaviour rather than prose.");
L.push("");

const markdown = `${L.join("\n")}\n`;

if (CHECK) {
  const abs = path.join(root, OUT);
  if (!fs.existsSync(abs) || fs.readFileSync(abs, "utf8") !== markdown) {
    console.error(`${OUT} is stale or missing; regenerate it.`);
    process.exit(1);
  }
  console.log(`Controlling legal decisions doc verified: ${record.decisions.length} decisions.`);
  process.exit(0);
}

fs.mkdirSync(path.join(root, path.dirname(OUT)), { recursive: true });
fs.writeFileSync(path.join(root, OUT), markdown);
console.log(`Wrote ${OUT} (${record.decisions.length} decisions)`);
