// Generates docs/partners/mvlp/MVLP_INTAKE_FIELD_MAP.md: the coverage table
// that shows, for every leaf input observed on MVLP's public form, what this
// product does with it and whether that is verified parity with the source
// ("observed"), an explicit product adaptation, or a detail the source left
// unresolved and this product decided. `--check` fails when the committed
// document is stale.
import fs from "node:fs";
import path from "node:path";
import { register } from "node:module";
import { fileURLToPath } from "node:url";

register("../lib/ts-esm-loader.mjs", import.meta.url);
const { INTAKE_FIELDS, INTAKE_STATEMENTS, INTAKE_SCHEMA_VERSION } = await import("../../src/lib/legal-aid/intake-schema.ts");

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const source = JSON.parse(fs.readFileSync(path.join(root, "data/legal-aid/source/MVLP_PUBLIC_FORM_FIELD_MAP.json"), "utf8"));
const out = path.join(root, "docs/partners/mvlp/MVLP_INTAKE_FIELD_MAP.md");

const escape = (value) => String(value ?? "").replace(/\|/g, "\\|").replace(/\n/g, " ");
const req = (value) => value === true ? "yes" : value === false ? "no" : "not established";
const byKey = Object.fromEntries(INTAKE_FIELDS.map((field) => [field.key, field]));
const counts = { observed: 0, adaptation: 0, unresolved: 0 };
const rows = [];
for (const leaf of source.fields) {
  const signatureLeaf = /^(\w+)\.(signature|date)$/.exec(leaf.key);
  if (signatureLeaf) {
    const statement = INTAKE_STATEMENTS.find((entry) => entry.key === signatureLeaf[1]);
    counts[statement.category] += 1;
    rows.push(`| ${escape(leaf.source_label ?? leaf.key)} | ${escape(leaf.source_control_type)} | ${req(leaf.source_required_reported)} | \`${leaf.key}\` → signature record (${signatureLeaf[2] === "signature" ? "signer name and method" : "signing time"}) | required when the statement applies | ${statement.category} | ${escape(statement.source.note)} |`);
    continue;
  }
  const field = byKey[leaf.key];
  counts[field.product.category] += 1;
  const requirement = field.product.requirement === "conditional" ? `conditional on ${field.product.conditionalOn.key} = ${field.product.conditionalOn.equals}` : field.product.requirement;
  rows.push(`| ${escape(leaf.source_label ?? field.source.label)} | ${escape(leaf.source_control_type ?? field.source.control)} | ${req(leaf.source_required_reported)} | \`${field.key}\` (${field.control}) | ${requirement}${field.product.allowUnknown ? ", \"I don't know\" allowed" : ""} | ${field.product.category} | ${escape(field.product.note)} |`);
}

const document = `# MVLP intake field map

Generated by \`scripts/legal-aid/generate-legal-aid-field-map.mjs\` from the observed
public form (${escape(source.source_title ?? "MVLP Self-Representation Expungement Clinic")}, inspected ${escape(source.inspection_date)})
and the product field map \`${INTAKE_SCHEMA_VERSION}\` in \`src/lib/legal-aid/intake-schema.ts\`.

Every one of the ${source.fields.length} leaf inputs observed on the public screen is listed once.
The category says what the product did with it:

- **observed**: verified parity with the observed source behaviour.
- **adaptation**: an explicit product change, with the reason.
- **unresolved**: the source did not establish the detail; this product decided it explicitly rather than guessing.

| Observed | Adaptation | Unresolved |
|---|---|---|
| ${counts.observed} | ${counts.adaptation} | ${counts.unresolved} |

A source "required" mark is a display observation, not tested server validation. "Not established" is never treated as optional.
The Social Security number is collected only in the confidential intake, in a restricted encrypted field with audited reveal;
it never appears in the answers document, lists, messages, routine exports or logs.

| Source label | Source control | Source required | Product field | Product rule | Category | Note |
|---|---|---|---|---|---|---|
${rows.join("\n")}

## Statements the applicant signs

| Statement | Shown when | Category | Source note |
|---|---|---|---|
${INTAKE_STATEMENTS.map((statement) => `| ${escape(statement.title)}: "${escape(statement.text)}" | ${statement.key === "citizenship_attestation" ? "citizenship answered Yes" : statement.key === "noncitizen_review_acknowledgment" ? "citizenship answered No" : "always"} | ${statement.category} | ${escape(statement.source.note)} |`).join("\n")}

Each signature records the statement version, the statement text hash, the applicant's answer version and answer hash, the signer's
typed name or drawn signature, and the time. A material edit supersedes every signature and the applicant signs again.
Only the applicant can sign; a volunteer's account cannot.

## Source limits carried forward

${(source.unverified_items ?? []).map((item) => `- ${escape(typeof item === "string" ? item : item.item ?? JSON.stringify(item))}`).join("\n") || "- (none recorded)"}
`;

if (process.argv.includes("--check")) {
  const current = fs.existsSync(out) ? fs.readFileSync(out, "utf8") : "";
  if (current !== document) { console.error(`stale: ${path.relative(root, out)}; regenerate with node scripts/legal-aid/generate-legal-aid-field-map.mjs`); process.exit(1); }
  console.log(`field map document current (${source.fields.length} leaves: ${counts.observed} observed, ${counts.adaptation} adaptation, ${counts.unresolved} unresolved).`);
} else {
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, document);
  console.log(`wrote ${path.relative(root, out)} (${source.fields.length} leaves: ${counts.observed} observed, ${counts.adaptation} adaptation, ${counts.unresolved} unresolved).`);
}
