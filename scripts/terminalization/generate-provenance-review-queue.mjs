#!/usr/bin/env node
/**
 * The re-review work queue, derived from the supersession record.
 *
 * The supersession record holds everything a reviewer needs and holds it in
 * two hundred kilobytes of JSON, which means in practice it holds it for a
 * verifier and not for a person. This renders the same facts as thirty-two
 * numbered work units: what to review, from which digest, against which
 * pathways, and why that scope and not a wider or narrower one.
 *
 * It is derived, so it cannot drift from the record: every field is read
 * from the supersession entry, nothing is restated from memory, and --check
 * refuses a stale copy.
 *
 * What this does NOT do is perform any review. A unit leaves this queue when
 * a reviewer's record is bound to its baseline and current digests; nothing
 * in this repository can bind one on a reviewer's behalf.
 *
 *   node scripts/terminalization/generate-provenance-review-queue.mjs
 *   node scripts/terminalization/generate-provenance-review-queue.mjs --check
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const SOURCE = "data/rcap-all50/terminalization-provenance-supersessions.json";
const OUT = "docs/record-clearing/terminalization-provenance-review-queue.md";
const check = process.argv.includes("--check");

const document = JSON.parse(fs.readFileSync(path.join(rootDir, SOURCE), "utf8"));

const jurisdiction = (profilePath) => path.basename(profilePath, ".json").split("-")[0];
const short = (sha) => String(sha).slice(0, 12);

// Priority 1 (targeted) first, because those are bounded and turn faster, and
// because they prove the review-record format, the digest binding, the
// computed scope and the C1/C2 consumption against real signed reviews before
// anyone spends weeks on a full profile. Within each band, widest first.
//
// The ordering is a workflow priority and nothing more. Both bands start at
// once, and no control reaches zero until every unit in both is satisfied.
const units = [...document.supersessions].sort((a, b) => {
  const rank = (e) => (e.disposition?.bucket === "FULL_REREVIEW_REQUIRED" ? 1 : 0);
  const weight = (e) => {
    const scope = e.disposition?.reviewScope;
    const iso =
      scope?.baselineSha256 === e.reviewedSha256
        ? e.delta?.isolation
        : (e.priorChain?.deltasFromOriginalCommittedDigests ?? []).find((d) => d.originalSha256 === scope?.baselineSha256)?.isolation;
    return iso ? iso.reviewedPathwaysDisturbed.length / Math.max(1, iso.pathwaysAtReview) : 0;
  };
  return rank(a) - rank(b) || weight(b) - weight(a) || jurisdiction(a.profilePath).localeCompare(jurisdiction(b.profilePath));
});

const L = [];
L.push("# Terminalization provenance re-review queue");
L.push("");
L.push(
  "Generated by `scripts/terminalization/generate-provenance-review-queue.mjs` from " +
    `\`${SOURCE}\`. Do not edit by hand — edit the record and regenerate.`
);
L.push("");
L.push("## Why this queue exists");
L.push("");
L.push(
  "Every unit below is a terminalization review that was performed against compiled-profile bytes the repository no longer has. " +
    "Lane C1 and lane C2 refuse each of them until the review named here exists and binds the exact digests named here. " +
    "That refusal is deliberate and it is safe to hold: no route in this queue carries commercial authority, so nothing here is sold, " +
    "checkout-enabled, sponsored or credit-consuming while the reviews are outstanding."
);
L.push("");
L.push("## The rule that sets each scope");
L.push("");
L.push(
  "Before this mechanism existed, provenance digests were moved in place — " +
    `${document.totals.priorUnrecordedRepinEvents} events across four commits in August 2026, none of which moved a \`reviewedAsOf\` date with it. ` +
    "So for many units the digest a record pins is **not** the digest its review saw. Where that is the case the review baseline is forced back " +
    "to the digest the record was first committed with, and where a unit has more than one such original, to the widest of them. Reviewing from the " +
    "pinned digest instead would re-review the later half of the change and leave the earlier half carrying a review nobody performed."
);
L.push("");
L.push("## Priority");
L.push("");
L.push(
  "**All 32 units are released to counsel at once.** The 20 full-profile reviews are not held behind the 12 targeted ones and should be " +
    "under way in parallel; nothing is gained by serialising them."
);
L.push("");
L.push(
  "**Priority 1 — the 12 targeted reviews.** Review only the machine-computed disturbed and newly added pathways and confirm the current " +
    "profile treatment is legally and source-correct. Do not re-review the excluded pathways. These are bounded, they should turn faster, " +
    "and they are the ones that prove the review-record format, the digest binding, the computed scope and the C1/C2 consumption all work " +
    "before weeks go into full-profile work."
);
L.push("");
L.push(
  "**Priority 2 — the 20 full-profile reviews.** Review the entire current compiled jurisdiction profile, because the whole-chain delta " +
    "disturbed too much of the previously reviewed surface to isolate any part of it safely."
);
L.push("");
L.push(
  "Priority is workflow order, not permission to postpone. Canonical `npm test` cannot reach zero until every review both controls require " +
    "is satisfied, so the second band is as blocking as the first."
);
L.push("");
L.push("## What every review must carry");
L.push("");
L.push("- who performed it, by name");
L.push("- the review date");
L.push("- the baseline digest (given per unit below)");
L.push("- the current digest (given per unit below)");
L.push("- the exact scope reviewed");
L.push("- the sources examined");
L.push("- findings and corrections, if any");
L.push("- an explicit approval **or hold**");
L.push("");
L.push("Two things a review must never do: change a historical `reviewedAsOf`, or replace a historical pin. Both are preserved permanently, and both are checked.");
L.push("");
L.push("## A hold is a result");
L.push("");
L.push(
  "**A review may come back `hold_correction_required`, and nobody should feel pressure to approve current bytes because a suite is red.** " +
    "If a profile is wrong, say so. The correct next step is to fix the profile — which moves its current digest, retires that unit as " +
    "`superseded_by_new_profile`, and opens a fresh unit against the corrected bytes for review. A held review is the mechanism working, " +
    "not a failure to deliver. Approving bytes a reviewer doubts would reproduce, with more ceremony, exactly the problem this queue exists to " +
    "correct."
);
L.push("");
L.push("## How a unit leaves this queue");
L.push("");
L.push("A reviewer produces a record, and the unit's `disposition.reviewRecord` is set to:");
L.push("");
L.push("```json");
L.push('{ "path": "<the review document>", "sha256": "<its digest>",');
L.push('  "bindsBaselineSha256": "<the baseline below>", "bindsCurrentSha256": "<the current digest below>" }');
L.push("```");
L.push("");
L.push(
  "Both bindings are checked. A review record that does not name both ends is a document about some other pair of digests, and is refused. " +
    "Nothing in this repository can write a `reviewRecord` on a reviewer's behalf."
);
L.push("");

const bucketCounts = document.totals.dispositionsByBucket;
L.push("## Summary");
L.push("");
L.push(`- **${units.length}** review units`);
L.push(`- **${bucketCounts.FULL_REREVIEW_REQUIRED}** full, **${bucketCounts.TARGETED_REREVIEW_REQUIRED}** targeted, **${bucketCounts.NO_SUBSTANTIVE_CHANGE}** immaterial`);
L.push(`- **${document.totals.pinsSuperseded}** of ${document.totals.recordsCarryingAProfilePin} pinned records are covered`);
L.push(`- **${units.filter((u) => u.priorChain?.pinnedDigestIsItselfARepin).length}** units review the whole original-digest chain because the pin was itself re-pinned`);
L.push(`- **${document.totals.reviewsOutstanding}** outstanding`);
L.push("");
L.push("| # | Priority | Jurisdiction | Disposition | Baseline | Pathways to review |");
L.push("|---|---|---|---|---|---|");
units.forEach((unit, index) => {
  const scope = unit.disposition.reviewScope;
  const target =
    unit.disposition.bucket === "FULL_REREVIEW_REQUIRED"
      ? "entire current profile"
      : `${scope.pathways.length} named`;
  const priority = unit.disposition.bucket === "FULL_REREVIEW_REQUIRED" ? 2 : 1;
  L.push(
    `| ${index + 1} | ${priority} | ${jurisdiction(unit.profilePath)} \`${short(unit.reviewedSha256)}\` | ${priority === 2 ? "FULL" : "TARGETED"} | ` +
      `${scope.baseline === "original_committed_digest" ? "original (re-pinned)" : "pinned"} | ${target} |`
  );
});
L.push("");
L.push("---");
L.push("");

units.forEach((unit, index) => {
  const scope = unit.disposition.reviewScope;
  const full = unit.disposition.bucket === "FULL_REREVIEW_REQUIRED";
  L.push(`## ${index + 1}. ${jurisdiction(unit.profilePath)} — ${unit.disposition.bucket} (Priority ${full ? 2 : 1})`);
  L.push("");
  L.push(`- **Profile:** \`${unit.profilePath}\``);
  L.push(`- **Review baseline:** \`${short(scope.baselineSha256)}\` — ${scope.baselineWhy}`);
  L.push(`- **Current bytes:** \`${short(scope.currentSha256)}\``);
  const asOf = unit.reviewedAsOf ?? (unit.reviewedAsOfAcrossRecords.join(", ") || "not recorded");
  L.push(`- **Review as of (preserved, not advanced):** ${asOf}`);
  L.push(`- **Records depending on it:** ${unit.recordCount}`);
  L.push(`- **Owner's reason for the bucket:** ${unit.disposition.rationale}`);
  if (unit.priorChain?.pinnedDigestIsItselfARepin) {
    L.push(
      `- **Prior silent re-pin:** yes. The pinned digest \`${short(unit.reviewedSha256)}\` was installed after this record was first committed, ` +
        "and the review date did not move with it. The baseline above is the original, so this review covers the whole chain."
    );
  }
  L.push("");
  if (full) {
    L.push("**Scope:** the entire current profile, against the operative legal and source evidence.");
    L.push("");
    L.push(
      `The prior review is **not** carried forward as substantive authority for any pathway — ${scope.priorReviewTreatment}`
    );
    L.push("");
    L.push(`At the baseline this profile had ${scope.pathwaysAtBaseline} pathways, of which ${scope.reviewedPathwaysDisturbed} were disturbed.`);
  } else {
    L.push(`**Scope:** ${scope.pathways.length} pathway(s) only. The other ${scope.excludedCount} reviewed at the baseline are excluded.`);
    L.push("");
    if (scope.disturbedExistingPathways.length > 0) {
      L.push("Disturbed since the review:");
      L.push("");
      for (const id of scope.disturbedExistingPathways) L.push(`- \`${id}\``);
      L.push("");
    }
    if (scope.newlyAddedPathways.length > 0) {
      L.push("Added since the review (never reviewed at all):");
      L.push("");
      for (const id of scope.newlyAddedPathways) L.push(`- \`${id}\``);
      L.push("");
    }
    L.push(`**Exclusion basis:** ${scope.excludedBecause}`);
  }
  L.push("");
  const delta = unit.delta;
  L.push(
    `**Measured delta from the pinned digest:** +${delta.counts.added} −${delta.counts.removed} ~${delta.counts.changed}, ` +
      `${delta.counts.operativeLeaves} operative. Dimensions touched: ${delta.dimensionsTouched.join(", ")}.`
  );
  const chain = (unit.priorChain?.deltasFromOriginalCommittedDigests ?? []).find((d) => d.originalSha256 === scope.baselineSha256);
  if (chain?.counts) {
    L.push("");
    L.push(
      `**Measured delta across the whole chain (what this review actually covers):** +${chain.counts.added} −${chain.counts.removed} ~${chain.counts.changed}, ` +
        `${chain.counts.operativeLeaves} operative, ${chain.isolation.reviewedPathwaysDisturbed.length}/${chain.isolation.pathwaysAtReview} pathways disturbed.`
    );
  }
  L.push("");
  L.push(`**Status:** \`${unit.disposition.reviewStatus}\`. Only \`approved_current_bytes\`, with a review record binding both digests above, satisfies the control; \`hold_correction_required\` is an equally valid outcome.`);
  L.push("");
});

const serialized = `${L.join("\n")}\n`;
const outPath = path.join(rootDir, OUT);

if (check) {
  if (!fs.existsSync(outPath) || fs.readFileSync(outPath, "utf8") !== serialized) {
    console.error("the provenance review queue is stale; re-run without --check");
    process.exit(1);
  }
  console.log(`provenance review queue current. ${units.length} unit(s), ${document.totals.reviewsOutstanding} outstanding.`);
  process.exit(0);
}

fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, serialized);
console.log(`wrote ${OUT} — ${units.length} review unit(s), ${document.totals.reviewsOutstanding} outstanding.`);
