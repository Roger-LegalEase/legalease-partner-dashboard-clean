// N1 denominator reconciliation.
//
// Three track counts are in circulation and v8 fact 3 states they are three
// snapshots rather than a contradiction. This script proves that from data and
// publishes the true denominator:
//
//   117  batch-1 authority crosswalk only (12 jurisdictions)
//   324  main's compiled jurisdiction profiles — what the runtime resolver sees
//   497  the nationwide registry on the integration branch — the true denominator
//
// It also records a finding the raw totals hide: the two universes do not share
// an identifier space. Authority tracks are short slugs such as `ak-courtview`;
// compiled pathways are descriptive slugs such as
// `confidentiality-of-acquittals-and-dismissals-as-22-35-030-administrative-rule-40`.
// No crosswalk between them is committed on main, so the reconciliation is by
// jurisdiction count, not by identity. Until a crosswalk exists, no per-track
// claim may be made about which of the 497 a compiled pathway serves.
//
// Reads the authority ledger produced by generate-rcap-authority-ledger.mjs and
// the compiled profiles in the working tree. Writes a markdown report. Exits 0;
// pass --strict to fail when the compiled count does not equal the denominator.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const ledgerPath = path.join(rootDir, "data/rcap-ledger/authority-ledger.json");
const profileDir = path.join(rootDir, "src/lib/rcap-engine/compiled/profiles");
const reportPath = path.join(rootDir, "docs/record-clearing/denominator-reconciliation.md");

const strict = process.argv.includes("--strict");

if (!fs.existsSync(ledgerPath)) {
  console.error("No authority ledger. Run npm run rcap:authority-ledger first.");
  process.exit(1);
}

const ledger = JSON.parse(fs.readFileSync(ledgerPath, "utf8"));

const authorityByJurisdiction = {};
for (const track of ledger.tracks) {
  authorityByJurisdiction[track.jurisdiction] =
    (authorityByJurisdiction[track.jurisdiction] || 0) + 1;
}

const compiledByJurisdiction = {};
let compiledIdSample = null;
for (const file of fs.readdirSync(profileDir).filter((f) => f.endsWith(".json"))) {
  const profile = JSON.parse(fs.readFileSync(path.join(profileDir, file), "utf8"));
  const code = String(
    (profile.jurisdiction && (profile.jurisdiction.code || profile.jurisdiction)) ||
      file.split("-")[0]
  ).toUpperCase();
  const pathways = profile.pathways || [];
  compiledByJurisdiction[code] = pathways.length;
  if (!compiledIdSample && pathways.length > 0) {
    compiledIdSample = pathways[0].trackId || pathways[0].id || pathways[0].pathwayId || null;
  }
}

const codes = [
  ...new Set([...Object.keys(authorityByJurisdiction), ...Object.keys(compiledByJurisdiction)])
].sort();

const rows = codes.map((code) => {
  const authority = authorityByJurisdiction[code] || 0;
  const compiled = compiledByJurisdiction[code] || 0;
  return { code, authority, compiled, delta: compiled - authority };
});

const authorityTotal = rows.reduce((s, r) => s + r.authority, 0);
const compiledTotal = rows.reduce((s, r) => s + r.compiled, 0);
const mismatched = rows.filter((r) => r.delta !== 0);
const surplus = rows.filter((r) => r.delta > 0);
const deficit = rows.filter((r) => r.delta < 0);
const zeroCompiled = rows.filter((r) => r.compiled === 0);

const authoritySample = ledger.tracks[0]?.trackId ?? null;

const lines = [];
lines.push("# RCAP Denominator Reconciliation");
lines.push("");
lines.push(
  `Generated by \`scripts/reconcile-rcap-denominator.mjs\` against authority ledger v${ledger.ledgerVersion} (\`${ledger.authority.ref}\` @ \`${(ledger.authority.commit || "").slice(0, 10)}\`, Master Library edition ${ledger.authority.authorityEdition}).`
);
lines.push("");
lines.push("## True denominator");
lines.push("");
lines.push(`**${authorityTotal}** — the nationwide registry on the integration branch.`);
lines.push("");
lines.push("| Figure | What it counts | Where it comes from |");
lines.push("| ---: | --- | --- |");
lines.push("| 117 | Batch-1 authority crosswalk, 12 jurisdictions only | `batch_1_expected_track_ids` in the Master Library reconciliation |");
lines.push(`| ${compiledTotal} | Compiled jurisdiction profiles on main — what the runtime resolver sees | \`src/lib/rcap-engine/compiled/profiles/*.json\` |`);
lines.push(`| **${authorityTotal}** | **Nationwide track registry — the denominator** | \`track-source-audit.json\` on the integration branch |`);
lines.push("");
lines.push("These are three snapshots of different universes, not competing counts of one.");
lines.push("");
lines.push("## Identifier spaces do not join");
lines.push("");
lines.push(
  "The registry and the compiled profiles use unrelated identifier schemes, and no crosswalk between them is committed on main:"
);
lines.push("");
lines.push(`- Authority track id: \`${authoritySample}\``);
lines.push(`- Compiled pathway id: \`${compiledIdSample}\``);
lines.push("");
lines.push(
  "Reconciliation below is therefore **by jurisdiction count only**. No claim may be made about which registry track a given compiled pathway serves until a crosswalk exists. Building that crosswalk is the prerequisite for any per-track coverage statement."
);
lines.push("");
lines.push("## Jurisdiction reconciliation");
lines.push("");
lines.push(
  `${mismatched.length} of ${rows.length} jurisdictions disagree. ${deficit.length} have fewer compiled pathways than registry tracks; ${surplus.length} have more; ${zeroCompiled.length} have none compiled.`
);
lines.push("");
if (surplus.length > 0) {
  lines.push(
    `Jurisdictions where main compiles **more** pathways than the registry lists — these cannot be explained as unfinished work and need identity resolution: ${surplus
      .map((r) => `${r.code} (+${r.delta})`)
      .join(", ")}.`
  );
  lines.push("");
}
lines.push("| Code | Registry tracks | Compiled pathways | Delta |");
lines.push("| --- | ---: | ---: | ---: |");
for (const row of rows) {
  lines.push(
    `| ${row.code} | ${row.authority} | ${row.compiled} | ${row.delta > 0 ? "+" : ""}${row.delta} |`
  );
}
lines.push(`| **Total** | **${authorityTotal}** | **${compiledTotal}** | **${compiledTotal - authorityTotal}** |`);
lines.push("");
lines.push("## Level predicates");
lines.push("");
lines.push("Published with the ledger so a level cannot be asserted without a machine check:");
lines.push("");
lines.push("| Level | Machine-checkable predicate | Current count |");
lines.push("| --- | --- | ---: |");
lines.push(
  "| 1 | Certified packet route: generates, stores, downloads, reopens. Requires private artifact storage, which does not exist yet, so this reads 0 by construction. | 0 |"
);
lines.push(
  `| 2 | Track carries a final disposition in the factory status computation (\`finalDisposition === true\`). | ${ledger.aggregates.tracksTerminal} |`
);
lines.push(
  `| 3 | Every track not at level 1 or 2. | ${ledger.aggregates.level3TracksRemaining} |`
);
lines.push("");
lines.push(
  "Level 1 and level 2 are computed from different sources and must not be summed against each other until the crosswalk above exists: level 1 is a runtime property of a compiled pathway, level 2 is a certification property of a registry track."
);
lines.push("");

fs.mkdirSync(path.dirname(reportPath), { recursive: true });
fs.writeFileSync(reportPath, `${lines.join("\n")}\n`, "utf8");

console.log(`trueDenominator        ${authorityTotal}`);
console.log(`compiledPathways       ${compiledTotal}`);
console.log(`delta                  ${compiledTotal - authorityTotal}`);
console.log(`jurisdictionsMismatched ${mismatched.length} / ${rows.length}`);
console.log(`surplusJurisdictions   ${surplus.map((r) => `${r.code}+${r.delta}`).join(" ") || "none"}`);
console.log(`identifierSpacesJoin   no (no crosswalk committed on main)`);
console.log(`report                 ${path.relative(rootDir, reportPath)}`);

if (strict && compiledTotal !== authorityTotal) {
  console.error(`\nStrict: compiled ${compiledTotal} != denominator ${authorityTotal}.`);
  process.exit(1);
}
