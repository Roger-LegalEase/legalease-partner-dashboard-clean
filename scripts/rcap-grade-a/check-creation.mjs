// Development boundary check. This is not the final integrated acceptance campaign.
import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import fs from 'node:fs';
const origin = process.env.RCAP_ACCEPTANCE_BASE_URL;
assert.equal(origin, 'http://127.0.0.1:3100');
assert.equal(process.env.NEXT_PUBLIC_SUPABASE_URL, 'http://127.0.0.1:54321');
assert.notEqual(process.env.VERCEL_ENV, 'production');
const access = JSON.parse(fs.readFileSync('/workspaces/training-modules-09-10/output/rcap-practice-access.json'));
const browser = await chromium.launch();
const context = await browser.newContext();
const page = await context.newPage();
page.setDefaultTimeout(60000);
const slug = `integrated-create-${Date.now().toString(36)}`;
try {
  await page.goto(`${origin}/sign-in?next=/internal/partners/provisioning/new`);
  await page.locator('input[type=email]').fill(access.owner.email);
  await page.locator('input[type=password]').fill(access.owner.password);
  await page.getByRole('button', { name: /^sign in$/i }).click();
  await page.waitForURL(url => url.pathname === '/internal/partners/provisioning/new');
  await page.getByLabel('Program operator', { exact: true }).selectOption('legalease_managed');
  await page.getByLabel('Public organization name', { exact: true }).fill('Integrated Isolated Practice');
  await page.getByLabel('Legal organization name', { exact: true }).fill('Integrated Isolated Practice');
  await page.getByLabel('Program name', { exact: true }).fill('Integrated Bilingual Screening');
  await page.getByLabel('Participant page address', { exact: false }).fill(slug);
  for (const state of ['California', 'District of Columbia', 'Virginia']) await page.getByRole('checkbox', { name: state, exact: true }).check();
  await page.getByLabel('Enable English and Spanish').check();
  await page.getByLabel('Internal creation reason', { exact: false }).fill('Owner-authorized isolated integrated workflow verification; no Production records.');
  await page.getByRole('button', { name: 'Review program', exact: true }).click();
  const created = page.waitForResponse(r => r.request().method() === 'POST' && r.url().endsWith('/api/internal/partners/provisioning'));
  await page.getByRole('button', { name: 'Create program', exact: true }).click();
  const response = await created;
  const receipt = await response.json();
  assert.equal(response.status(), 200, JSON.stringify(receipt));
  await page.waitForURL(u => u.pathname === `/internal/partners/onboarding/${slug}`);
  await page.getByRole('heading', { name: 'Configure program', exact: true }).waitFor();
  const saved = page.waitForResponse(r => r.request().method() === 'POST' && r.url().endsWith('/configuration'));
  await page.getByRole('button', { name: 'Save program', exact: true }).click();
  const savedResponse = await saved;
  const state = await savedResponse.json();
  assert.equal(savedResponse.status(), 200, JSON.stringify(state));
  assert.equal(state.preparationError, null);
  assert.deepEqual(state.configuration.data.geography_audience_language_accessibility.jurisdictions, ['CA', 'DC', 'VA']);
  assert.equal(state.operations.view.materials.length, 2);
  assert.deepEqual(state.operations.view.materials.find(m => m.type === 'co_branded_page_configuration').document.pagePreview.missing, []);
  await page.getByRole('link', { name: 'View Participant Page', exact: true }).click();
  await page.locator('#participant-page-preview').getByRole('button', { name: 'Mobile', exact: true }).click();
  await page.locator('#participant-page-preview').getByRole('button', { name: 'Español', exact: true }).click();
  const out = 'artifacts/rcap-grade-a-final/ba81792225d6d82ef57c104061e9d5eb9d7db395/server';
  fs.writeFileSync(`${out}/creation-development-check.json`, JSON.stringify({ kind: 'DEVELOPMENT_CHECK_NOT_FINAL_ACCEPTANCE', slug, created: receipt.result, source: 'working-tree', jurisdictions: ['CA', 'DC', 'VA'], provider: 'approved standard bilingual copy; no AI request', materials: state.operations.view.materials.map(({id,type,version,hash})=>({id,type,version,hash})), canStart: state.operations.canStart }, null, 2));
  console.log(JSON.stringify({result: 'PASS', kind: 'development creation/save boundary', slug, materials: state.operations.view.materials.length, canStart: state.operations.canStart}));
} finally { await browser.close(); }
