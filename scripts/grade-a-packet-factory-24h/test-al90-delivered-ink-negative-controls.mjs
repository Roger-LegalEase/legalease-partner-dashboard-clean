import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { PDFDocument, StandardFonts } from 'pdf-lib';
import { makeCorpusEntryResolver } from '../lib/corpus-index-paths.mjs';
import { measureAl90Packet } from '../build-census-v1-al-felony-nonconviction-90-set.mjs';
const ROOT=path.resolve(new URL('../..',import.meta.url).pathname);
const dir=path.join(ROOT,'data/rcap-all50/overlays/census-v1/al/al-felony-nonconviction-90-set--official-pdf-fill');
const read=n=>JSON.parse(fs.readFileSync(path.join(dir,n)));
const index=JSON.parse(fs.readFileSync(path.join(ROOT,'data/rcap-all50/local-source-corpus-index.json')));
const resolver=makeCorpusEntryResolver(index,{repoRoot:ROOT,masterLibraryRoot:process.env.MASTER_LIBRARY_SOURCE_DIR});
const sources=read('source-receipt.json').sources.map(s=>{const entry=index.entries.find(e=>e.path===s.path);assert.ok(entry);const bytes=fs.readFileSync(resolver.resolve(entry));assert.equal(crypto.createHash('sha256').update(bytes).digest('hex'),s.sha256);return {...s,bytes};});
const packet={writes:read('reports/actual-writes.json').documents.flatMap(d=>d.actualWrites),refusals:read('production-field-map.json').refusals};
const original=fs.readFileSync(path.join(dir,'fixtures/canonical.pdf'));
const good=await measureAl90Packet(original,sources,packet);
assert.equal(good.fieldsMeasured,216);assert.equal(good.intendedInkFieldsWhoseInkWasFoundInOutputBytes,30);
assert.deepEqual(good.refusedFieldsWithInk,[]);assert.deepEqual(good.incompleteValues,[]);assert.deepEqual(good.invisibleWrites,[]);
const source=await PDFDocument.load(sources[0].bytes),widget=source.getForm().getTextField('Text2').acroField.getWidgets()[0];
const sourcePage=source.getPages().findIndex(p=>p.ref.toString()===widget.P()?.toString());assert.ok(sourcePage>=0);
assert.ok(packet.refusals.some(r=>r.fieldId==='CR-65:Text2'));const rect=widget.getRectangle();
const corrupt=await PDFDocument.load(original),font=await corrupt.embedFont(StandardFonts.Helvetica);
corrupt.getPage(sourcePage).drawText('9999',{x:rect.x+2,y:rect.y+3,size:5,font});
const injected=await measureAl90Packet(await corrupt.save(),sources,packet);
assert.ok(injected.refusedFieldsWithInk.some(r=>r.fieldId==='CR-65:Text2'),'Actual added ink on refused SSN field must fail');
const wrongPacket=structuredClone(packet);const target=wrongPacket.writes.find(w=>w.drawnText);target.drawnText='WRONG EXPECTED VALUE';
const wrong=await measureAl90Packet(original,sources,wrongPacket);
assert.ok(wrong.incompleteValues.some(r=>r.fieldId===target.fieldId),'Actual wrong expected value must fail');
console.log(JSON.stringify({fieldsMeasured:good.fieldsMeasured,actualProtectedInkInjectionDetected:true,wrongExpectedDetected:true,packetBytesUnchanged:true}));
