import assert from 'node:assert/strict';
import fs from 'node:fs';
import { register } from 'node:module';
register('./lib/ts-esm-loader.mjs', import.meta.url);
const { getProfileByJurisdiction } = await import('../src/lib/rcap-engine/profile-registry.ts');
const { withWestVirginia407Procedure } = await import('../src/lib/rcap-engine/research-limited-route-procedures.ts');
const { packetPlanForPathway } = await import('../src/lib/rcap-engine/packet-planner.ts');
const { resolvePacketRoute } = await import('../src/lib/rcap/documents/packet-route-resolver.ts');
const { getCurrentFulfillmentRecord } = await import('../src/lib/rcap/fulfillment/grade-a-registry.ts');
const { WEST_VIRGINIA_407_ROUTE: route } = await import('../src/lib/rcap-engine/west-virginia-407-facts.ts');
const raw = JSON.parse(fs.readFileSync('src/lib/rcap-engine/compiled/profiles/WV-west-virginia.json'));
const before = JSON.stringify(raw);
const profile = getProfileByJurisdiction('WV');
const id = route.slice(3);
const pathway = profile.pathways.find(p => p.id === id);
const original = raw.pathways.find(p => p.id === id);
assert(pathway.summary.includes('supporting affidavit'));
assert(pathway.summary.includes('court determines probation violations'));
assert(pathway.summary.includes('attach the actual orders'));
assert(!pathway.summary.includes('SCA-C903'));
assert.deepEqual(pathway.legalAuthority, original.legalAuthority, 'Existing adopted legal decision must remain intact');
const plan = packetPlanForPathway(profile, id);
assert.equal(plan.mode, 'state_specific_custom_packet_from_source_rules');
assert.equal(plan.formMappingStatus, 'custom_or_manual_mapping_required');
assert.deepEqual(plan.sourceFormIds, []);
const derived = withWestVirginia407Procedure(raw);
for (const p of raw.pathways.filter(p => p.id !== id)) assert.deepEqual(derived.pathways.find(row => row.id === p.id), p);
for (const p of raw.packetGenerator.pathways.filter(p => p.pathwayId !== id)) assert.deepEqual(derived.packetGenerator.pathways.find(row => row.pathwayId === p.pathwayId), p);
assert.equal(JSON.stringify(raw), before, 'Derived correction must preserve the compiled source');
assert.equal(getCurrentFulfillmentRecord(route), null, 'A corrected source plan is not fulfillment authority');
const resolved = resolvePacketRoute({ state: 'WV', pathway: id });
assert.equal(resolved.sellable, false);
assert.equal(resolved.creditConsumable, false);
console.log('PASS WV407 actual registry/planner: exact custom package, unchanged adopted authority/source/other routes, existing commercial refusal preserved. No hosted or production claim.');
